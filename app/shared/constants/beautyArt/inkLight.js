// ── drawing kit ─────────────────────────────────────────────────────────
const u = (id) => `url(#${id})`;
const at = (extra) => (extra ? ` ${extra}` : "");
const P = (d, fill, extra = "") => `<path d="${d}" fill="${fill}"${at(extra)}/>`;
const L = (d, color, width, extra = "") =>
  `<path d="${d}" fill="none" stroke="${color}" stroke-width="${width}" stroke-linecap="round" stroke-linejoin="round"${at(extra)}/>`;
const O = (cx, cy, r, fill, extra = "") => `<circle cx="${cx}" cy="${cy}" r="${r}" fill="${fill}"${at(extra)}/>`;
const E = (cx, cy, rx, ry, fill, extra = "") => `<ellipse cx="${cx}" cy="${cy}" rx="${rx}" ry="${ry}" fill="${fill}"${at(extra)}/>`;
const R = (x, y, w, h, r, fill, extra = "") => `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${r}" fill="${fill}"${at(extra)}/>`;
const G = (transform, inner) => `<g transform="${transform}">${inner}</g>`;
const rot = (deg, cx, cy, inner) => G(`rotate(${deg} ${cx} ${cy})`, inner);
// white light catch
const hi = (d, opacity = 0.55) => P(d, C.n0, `opacity="${opacity}"`);
const hiLine = (d, width = 4, opacity = 0.55) => L(d, C.n0, width, `opacity="${opacity}"`);
// edge for white objects so they stand on white cards
const EDGE = `stroke="${C.v400}" stroke-width="3.5" stroke-linejoin="round"`;
// ring as one even-odd path
const ring = (cx, cy, outer, inner) =>
  `M${cx - outer} ${cy}a${outer} ${outer} 0 1 0 ${outer * 2} 0a${outer} ${outer} 0 1 0 ${-outer * 2} 0Z` +
  `M${cx - inner} ${cy}a${inner} ${inner} 0 1 0 ${inner * 2} 0a${inner} ${inner} 0 1 0 ${-inner * 2} 0Z`;
// four-point twinkle
const twinkle = (x, y, r, fill) => {
  const k = r * 0.22;
  return P(`M${x} ${y - r}C${x + k} ${y - k} ${x + k} ${y - k} ${x + r} ${y}C${x + k} ${y + k} ${x + k} ${y + k} ${x} ${y + r}C${x - k} ${y + k} ${x - k} ${y + k} ${x - r} ${y}C${x - k} ${y - k} ${x - k} ${y - k} ${x} ${y - r}Z`, fill);
};
// a lock of hair hanging from y0 to y1 around x, `wave` bends it
const lock = (x, y0, y1, width, wave, fill) => {
  const h = width / 2;
  const span = y1 - y0;
  return P(`M${x - h} ${y0}C${x - h - wave} ${y0 + span * 0.3} ${x - h + wave} ${y0 + span * 0.62} ${x - h * 0.45} ${y1 - 4}Q${x} ${y1 + 4} ${x + h * 0.45} ${y1 - 4}C${x + h + wave} ${y0 + span * 0.62} ${x + h - wave} ${y0 + span * 0.3} ${x + h} ${y0}Q${x} ${y0 - 6} ${x - h} ${y0}Z`, fill);
};

