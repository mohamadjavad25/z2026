const lin = (id, list, x1 = 0.2, y1 = 0, x2 = 0.8, y2 = 1) =>
  `<linearGradient id="${id}" x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}">${stops(list)}</linearGradient>`;

