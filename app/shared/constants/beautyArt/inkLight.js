// frfro colour system (docs/DESIGN_SYSTEM.md, «آیکن خدمات»).
//
// Rules every drawing follows:
// - 128x128 canvas, no tile or floor shadow; the object fills about 8-120.
// - Only the brand ramps below: pink, violet, the neutral ramp and white, plus
//   one warm skin tone for hands, feet and faces.
// - Read at 28px: one main object, at most one helper object, no hairlines
//   (nothing thinner than 5 units), no decorative sparkles.
// - Read on day and night cards: the outer silhouette is a mid tone (pink 300-600,
//   violet 300-600, skin) or white with a violet edge. Dark ink only inside.
// - Light comes from the top left: each fill is a gradient from light to deep.
// Each entry is inner SVG; ICON_DEFS is prepended by beautyEmoji.js.

